"""Evolution of the AST proposer's typed grammar architecture for V68.

The candidate bank is generated by a fixed superset grammar.  An architecture
genome then defines the executable sub-grammar exposed to the proposer.  This
keeps the experiment compute-matched and auditable while making the evolved
object larger than a linear ranking vector: it changes which typed operators
and complexity levels are available at all.
"""

from __future__ import annotations

import copy
import json
import random

from .common import canonical
from .invented_space import _split_atoms
from .semantic_invention import parse_span


GRAMMAR_OPS = ("add", "sub", "mul", "div", "mod", "xor", "shr", "mask", "not")
RANK_MODES = ("frozen", "shortest", "complexity", "novelty")
MAX_COMPLEXITIES = (170, 180, 190, 205, 230, 999)


def _walk(node, operations):
    if isinstance(node, dict):
        op = node.get("op")
        if op in GRAMMAR_OPS:
            operations.add(op)
        for value in node.values():
            _walk(value, operations)
    elif isinstance(node, list):
        for value in node:
            _walk(value, operations)


def candidate_operations(program: str) -> tuple[str, ...]:
    """Return the typed numeric operators used by a serialized span program."""
    operations = set()
    if program.startswith("Concat(") and program.endswith(")"):
        for atom in _split_atoms(program[7:-1]):
            span = parse_span(atom)
            if span is None:
                continue
            for boundary in span:
                _walk(boundary.get("predicate"), operations)
    return tuple(sorted(operations))


def candidate_complexity(program: str) -> int:
    values = []
    if program.startswith("Concat(") and program.endswith(")"):
        for atom in _split_atoms(program[7:-1]):
            span = parse_span(atom)
            if span is None:
                continue
            for boundary in span:
                predicate = boundary.get("predicate")
                if isinstance(predicate, dict) and isinstance(predicate.get("complexity"), int):
                    values.append(predicate["complexity"])
    return max(values, default=999)


def annotate_candidates(candidates: list[dict]) -> list[dict]:
    """Add deterministic architecture features to the protected candidate bank."""
    annotated = []
    for candidate in candidates:
        row = dict(candidate)
        row["grammar_ops"] = list(candidate_operations(candidate["program"]))
        row["grammar_complexity"] = candidate_complexity(candidate["program"])
        annotated.append(row)
    return annotated


def architecture_allows(candidate: dict, architecture: dict) -> bool:
    return (set(candidate.get("grammar_ops", candidate_operations(candidate["program"])))
            <= set(architecture["enabled_ops"])
            and candidate.get("grammar_complexity", candidate_complexity(candidate["program"]))
            <= architecture["max_complexity"])


def _frozen_score(program: str) -> int:
    # Exact V67 frozen policy, retained as the compute-matched control.
    return (100 * program.count("div") + 10 * program.count("mul") +
            5 * program.count("xor") + 2 * program.count("mask") +
            program.count("shr") - len(program))


def architecture_score(candidate: dict, architecture: dict) -> tuple:
    program = candidate["program"]
    mode = architecture["rank_mode"]
    if mode == "frozen":
        # Match meta_ast.choose_candidate exactly for the frozen control.
        return (_frozen_score(program), -len(program), program)
    if mode == "shortest":
        return (-len(program), -candidate["grammar_complexity"], program)
    if mode == "complexity":
        return (-candidate["grammar_complexity"], -len(program), program)
    # Novelty mode prefers richer typed expressions but still terminates on a
    # deterministic tie-break, so it cannot exploit iteration order.
    novelty = sum(program.count(op) for op in GRAMMAR_OPS)
    return (novelty, -candidate["grammar_complexity"], -len(program), program)


def choose_architecture_candidate(candidates: list[dict], architecture: dict) -> dict | None:
    allowed = [candidate for candidate in candidates if architecture_allows(candidate, architecture)]
    return max(allowed, key=lambda candidate: architecture_score(candidate, architecture)) if allowed else None


def canonical_architecture(architecture: dict) -> dict:
    return {"enabled_ops": sorted(set(architecture["enabled_ops"])),
            "max_complexity": int(architecture["max_complexity"]),
            "rank_mode": architecture["rank_mode"]}


def initial_population(seed: int, size: int = 24) -> list[dict]:
    rng = random.Random(seed)
    population = [
        {"enabled_ops": list(GRAMMAR_OPS), "max_complexity": 999, "rank_mode": "frozen"},
        {"enabled_ops": ["add", "mul", "div", "mod"], "max_complexity": 205, "rank_mode": "complexity"},
        {"enabled_ops": ["add", "mul", "div", "mod", "xor"], "max_complexity": 230, "rank_mode": "novelty"},
        {"enabled_ops": ["add", "mul", "div", "mod"], "max_complexity": 999, "rank_mode": "shortest"},
    ]
    while len(population) < size:
        enabled = [op for op in GRAMMAR_OPS if rng.random() < 0.65]
        if not enabled:
            enabled = [rng.choice(GRAMMAR_OPS)]
        population.append({"enabled_ops": enabled,
                           "max_complexity": rng.choice(MAX_COMPLEXITIES),
                           "rank_mode": rng.choice(RANK_MODES[1:])})
    return [canonical_architecture(architecture) for architecture in population]


def _development_score(architecture: dict, development_pools: list[dict]) -> tuple[int, int, int]:
    correct = 0
    selected = 0
    for pool in development_pools:
        candidate = choose_architecture_candidate(pool["candidates"], architecture)
        if candidate is not None:
            selected += 1
            correct += int(candidate.get("oracle_correct", False))
    # Simplicity is only a tie-break, never a substitute for task accuracy.
    return correct, selected, -len(architecture["enabled_ops"])


def evolve(population: list[dict], development_pools: list[dict], generations: int = 5,
           elite_count: int = 5, seed: int = 0) -> tuple[dict, list[dict]]:
    rng = random.Random(seed)
    current = [copy.deepcopy(architecture) for architecture in population]
    trace = []
    for generation in range(generations):
        scored = sorted(((_development_score(architecture, development_pools), architecture)
                         for architecture in current), key=lambda row: (row[0], canonical(row[1])), reverse=True)
        trace.append({"generation": generation, "best_score": list(scored[0][0]),
                      "best_architecture": scored[0][1], "population": len(current)})
        elites = [architecture for _score, architecture in scored[:elite_count]]
        next_population = [copy.deepcopy(architecture) for architecture in elites]
        while len(next_population) < len(current):
            left, right = rng.choice(elites), rng.choice(elites)
            enabled = [op for op in GRAMMAR_OPS
                       if (op in left["enabled_ops"] if rng.random() < 0.5 else op in right["enabled_ops"])]
            if not enabled:
                enabled = [rng.choice(GRAMMAR_OPS)]
            if rng.random() < 0.65:
                op = rng.choice(GRAMMAR_OPS)
                if op in enabled and len(enabled) > 1:
                    enabled.remove(op)
                elif op not in enabled:
                    enabled.append(op)
            complexity = left["max_complexity"] if rng.random() < 0.5 else right["max_complexity"]
            if rng.random() < 0.30:
                complexity = rng.choice(MAX_COMPLEXITIES)
            mode = left["rank_mode"] if rng.random() < 0.5 else right["rank_mode"]
            if rng.random() < 0.20:
                mode = rng.choice(RANK_MODES[1:])
            next_population.append(canonical_architecture({"enabled_ops": enabled,
                                                             "max_complexity": complexity,
                                                             "rank_mode": mode}))
        current = next_population
    scored = sorted(((_development_score(architecture, development_pools), architecture)
                     for architecture in current), key=lambda row: (row[0], canonical(row[1])), reverse=True)
    trace.append({"generation": generations, "best_score": list(scored[0][0]),
                  "best_architecture": scored[0][1], "population": len(current)})
    return scored[0][1], trace
